-- Admin console: private notes on an account, and the proof a mentor applicant uploads (live camera photo and up to 3 documents).
-- Proof images are stored as text: base64, encrypted with FIELD_ENCRYPTION_KEY when that key is set.
CREATE TABLE IF NOT EXISTS admin_user_notes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id text NOT NULL REFERENCES ledgerline_accounts(firebase_uid) ON DELETE CASCADE,
  author_id text NOT NULL,
  body text NOT NULL CHECK (char_length(body) BETWEEN 1 AND 1000),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS admin_user_notes_user ON admin_user_notes (user_id, created_at DESC);

ALTER TABLE mentor_verifications ADD COLUMN IF NOT EXISTS live_photo text, ADD COLUMN IF NOT EXISTS live_photo_at timestamptz;

CREATE TABLE IF NOT EXISTS mentor_documents (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  verification_id uuid NOT NULL REFERENCES mentor_verifications(id) ON DELETE CASCADE,
  kind text NOT NULL CHECK (kind IN ('certificate','id','other')),
  label text NOT NULL DEFAULT '' CHECK (char_length(label) <= 80),
  image text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS mentor_documents_verification ON mentor_documents (verification_id, created_at);
