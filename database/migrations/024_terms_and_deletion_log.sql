-- Evidence of what each person agreed to, and a record that deletion requests were carried out.
CREATE TABLE IF NOT EXISTS terms_acceptances (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id text NOT NULL REFERENCES ledgerline_accounts(firebase_uid) ON DELETE CASCADE,
  document text NOT NULL CHECK (document IN ('terms','privacy')),
  version text NOT NULL CHECK (char_length(version) BETWEEN 1 AND 40),
  method text NOT NULL CHECK (method IN ('signup_checkbox')),
  accepted_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (user_id, document, version)
);
CREATE INDEX IF NOT EXISTS terms_acceptances_user_idx ON terms_acceptances (user_id);

-- Append-only: an accepted version can be added to but never rewritten.
CREATE OR REPLACE FUNCTION terms_acceptances_no_update() RETURNS trigger AS $$
BEGIN RAISE EXCEPTION 'terms_acceptances is append-only'; END $$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS terms_acceptances_append_only ON terms_acceptances;
CREATE TRIGGER terms_acceptances_append_only BEFORE UPDATE ON terms_acceptances
  FOR EACH ROW EXECUTE FUNCTION terms_acceptances_no_update();

-- No personal data: only a one-way hash of the account id, so a request can be shown to have been honoured.
CREATE TABLE IF NOT EXISTS account_deletions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_hash text NOT NULL,
  requested_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz NOT NULL DEFAULT now(),
  rows_removed integer NOT NULL DEFAULT 0
);
