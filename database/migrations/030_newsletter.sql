-- The trading newsletter: double opt-in subscribers, issues, and a consent record for each opt-in.
CREATE TABLE IF NOT EXISTS newsletter_subscribers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL UNIQUE CHECK (char_length(email) BETWEEN 3 AND 254 AND email = lower(email)),
  user_id text REFERENCES ledgerline_accounts(firebase_uid) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','subscribed','unsubscribed','bounced')),
  topics text[] NOT NULL DEFAULT ARRAY['Market wrap','Process lessons','Journal and sizing tips','Product updates'],
  frequency text NOT NULL DEFAULT 'weekly' CHECK (frequency IN ('weekly','weekdays','monthly')),
  confirm_expires_at timestamptz,
  confirmed_at timestamptz,
  unsubscribed_at timestamptz,
  last_sent_at timestamptz,
  resend_day date,
  resend_count smallint NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS newsletter_subscribers_user_idx ON newsletter_subscribers (user_id) WHERE user_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS newsletter_subscribers_status_idx ON newsletter_subscribers (status);

CREATE TABLE IF NOT EXISTS newsletter_issues (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  number integer NOT NULL UNIQUE,
  title text NOT NULL CHECK (char_length(title) BETWEEN 1 AND 140),
  slug text NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9-]{1,80}$'),
  topic text NOT NULL CHECK (topic IN ('Market wrap','Process lessons','Journal and sizing tips','Product updates')),
  body_md text NOT NULL CHECK (char_length(body_md) BETWEEN 1 AND 20000),
  status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','scheduled','sent')),
  scheduled_at timestamptz,
  published_at timestamptz,
  sent_count integer NOT NULL DEFAULT 0,
  failed_count integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);
-- Who has already been sent an issue, so a retry never sends twice.
CREATE TABLE IF NOT EXISTS newsletter_deliveries (
  issue_id bigint NOT NULL REFERENCES newsletter_issues(id) ON DELETE CASCADE,
  subscriber_id bigint NOT NULL REFERENCES newsletter_subscribers(id) ON DELETE CASCADE,
  sent_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (issue_id, subscriber_id)
);
CREATE TABLE IF NOT EXISTS newsletter_consents (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL,
  user_id text,
  action text NOT NULL CHECK (action IN ('subscribe','confirm','unsubscribe','bounce','complaint')),
  wording text NOT NULL DEFAULT '',
  template_version text NOT NULL DEFAULT '',
  ip_hash text,
  at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS newsletter_consents_email_idx ON newsletter_consents (email, at DESC);
-- Webhook events already handled (bounces and complaints can be delivered twice).
CREATE TABLE IF NOT EXISTS newsletter_events (event_id text PRIMARY KEY, at timestamptz NOT NULL DEFAULT now());
