-- Help-centre tickets. A ticket can come from a signed-in user (user_id set, deleted with the account)
-- or from a visitor who only gave an email address. `diagnostics` holds the technical details the
-- help form collects (browser, screen, page, recent errors) so the team can reproduce a problem.
CREATE TABLE IF NOT EXISTS support_tickets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id text REFERENCES ledgerline_accounts(firebase_uid) ON DELETE CASCADE,
  email text NOT NULL CHECK (char_length(email) <= 254),
  topic text NOT NULL CHECK (topic IN ('Bug','Billing','Feature idea','Data request')),
  priority text NOT NULL CHECK (priority IN ('Low','Normal','Urgent')),
  subject text NOT NULL CHECK (char_length(subject) BETWEEN 1 AND 100),
  status text NOT NULL DEFAULT 'open' CHECK (status IN ('open','in_progress','resolved')),
  diagnostics jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  resolved_at timestamptz
);
CREATE INDEX IF NOT EXISTS support_tickets_status_idx ON support_tickets (status, updated_at DESC);
CREATE INDEX IF NOT EXISTS support_tickets_user_idx ON support_tickets (user_id, updated_at DESC);

CREATE TABLE IF NOT EXISTS support_ticket_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id bigint NOT NULL REFERENCES support_tickets(id) ON DELETE CASCADE,
  author text NOT NULL CHECK (author IN ('user','admin')),
  body text NOT NULL CHECK (char_length(body) BETWEEN 1 AND 2000),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS support_ticket_messages_ticket_idx ON support_ticket_messages (ticket_id, id);
